      <li><strong>Day 4: Rishikesh – The Yoga Capital of the World:</strong>
        - Visit the sacred Triveni Ghat for the evening Ganga Aarti.
        - Explore Laxman Jhula and Ram Jhula.
        - Enjoy river rafting on the Ganges or take a nature walk.</li>

      <li><strong>Day 5: Haridwar – Spiritual Experience:</strong>
